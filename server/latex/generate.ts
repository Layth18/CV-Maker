export function generateProject({ profile, cv, photo }: GenerateInput): GeneratedProject {
  const ctx = new Ctx(cv.language);
  const template = getTemplate(cv.templateId);
  const L = cv.layout;
  const twoCols = L.columns === 2;
  let header = L.headerStyle;
  if (!twoCols && (header === 'sidebar' || header === 'main')) header = 'left';

  const files: GeneratedFile[] = [];
  const sectionInputs: { column: 'main' | 'sidebar'; path: string }[] = [];

  for (const s of cv.sections) {
    if (!s.visible) continue;
    const inSidebar = twoCols && s.column === 'sidebar';
    const body = sectionBody(ctx, profile, s, inSidebar);
    if (body === null) continue;
    const customTitle = isCustomKey(s.key)
      ? ctx.t(profile.customSections.find((c) => `custom:${c.id}` === s.key)?.title, 'a custom section title')
      : undefined;
    const title = tex(sectionLabel(cv, s, customTitle));
    const name = sectionFileName(s, profile);
    const path = `sections/${name}.tex`;
    files.push({
      path,
      content: `${HEADER_COMMENT(`sections/${name}.tex -- ${title.replace(/\\/g, '')}`)}\n\\cvsection{${title}}\n\n${body}\n`,
    });
    sectionInputs.push({ column: inSidebar ? 'sidebar' : 'main', path: `sections/${name}` });
  }

  const hasPhoto = Boolean(photo && L.showPhoto);
  const assets = hasPhoto && photo ? [{ path: `assets/photo.${photo.ext}`, sourcePath: photo.sourcePath }] : [];
  const extraPreamble = cv.advanced.extraPreamble.trim();

  // --- main.tex --------------------------------------------------------------
  const paper = L.paper === 'letter' ? 'letter' : 'a4';
  const m: string[] = [];
  m.push('% !TEX program = xelatex');
  m.push(HEADER_COMMENT(`main.tex -- ${cv.name.replace(/[\r\n]/g, ' ')}`).trimEnd());
  m.push(`% Template: ${template.name}  |  Theme: ${cv.theme}  |  Language: ${cv.language.toUpperCase()}  |  Layout: ${twoCols ? 'two columns' : 'single column'}`);
  m.push('');
  m.push(`\\documentclass[fontsize=${num(cv.typography.fontSize, 1)}pt, paper=${paper}, parskip=false]{scrartcl}`);
  m.push('');
  m.push('\\usepackage{cvcore}            % shared CV components');
  m.push(`\\usepackage{cvtheme-${cv.theme}}   % theme: section and entry styles`);
  m.push('\\input{settings}               % geometry, fonts, colors, spacing');
  m.push('\\input{personal_info}          % name, headline, contacts, photo');
  if (extraPreamble) m.push('\\input{custom_preamble}        % your advanced LaTeX additions');
  m.push('');
  m.push('\\begin{document}');

  const headerCmd: Record<string, string> = {
    banner: '\\cvheaderbanner',
    left: '\\cvheaderleft',
    centered: '\\cvheadercentered',
    sidebar: '\\cvheadersidebar',
    main: '\\cvheadermain',
  };
  const inputs = (column: 'main' | 'sidebar') =>
    sectionInputs.filter((s) => s.column === column).map((s) => `\\input{${s.path}}`);

  if (!twoCols) {
    m.push(headerCmd[header]);
    m.push('\\cvbodyalign');
    m.push('\\cvcolumnstart');
    m.push('');
    m.push(...inputs('main'));
  } else {
    if (header !== 'sidebar' && header !== 'main') {
      m.push(headerCmd[header]);
      m.push('');
    }
    const sidebarBlock = [
      '% ---- Sidebar ----------------------------------------------------------',
      '\\cvsidebarstyle',
      '\\cvmarksidebartop',
      ...(header === 'sidebar' ? ['\\cvheadersidebar'] : []),
      '\\cvcolumnstart',
      ...inputs('sidebar'),
    ];
    const mainBlock = [
      '% ---- Main column ------------------------------------------------------',
      '\\cvmainstyle',
      ...(header === 'main' ? ['\\cvheadermain'] : []),
      '\\cvcolumnstart',
      ...inputs('main'),
    ];
    const [first, second] = L.sidebarPosition === 'left' ? [sidebarBlock, mainBlock] : [mainBlock, sidebarBlock];
    m.push('\\begin{paracol}{2}');
    m.push(...first);
    m.push('');
    m.push('\\switchcolumn');
    m.push(...second);
    m.push('\\end{paracol}');
  }
  m.push('');
  m.push('\\end{document}');

  files.unshift(
    { path: 'main.tex', content: m.join('\n') + '\n' },
    { path: 'settings.tex', content: settingsFile(cv, cv.theme) },
    { path: 'personal_info.tex', content: personalFile(ctx, profile, cv, photo) },
  );
  if (extraPreamble) {
    files.push({
      path: 'custom_preamble.tex',
      content: `${HEADER_COMMENT('custom_preamble.tex -- advanced LaTeX added in the editor')}\n${cv.advanced.extraPreamble.replace(/\r\n?/g, '\n')}\n`,
    });
  }

  // The sidebar background (TikZ remember picture) and "Page x of y" read positions from the
  // .aux file, which only exists after a first run; other layouts settle in one run.
  const minPasses = (twoCols && L.sidebarFilled) || L.pageNumbering === 'of-total' ? 2 : 1;

  return { mainFile: 'main.tex', files, assets, notes: [...ctx.notes], minPasses };
}
