function sectionBody(ctx: Ctx, profile: Profile, s: SectionConfig, inSidebar: boolean): string | null {
  // Individual skills, bullets and lines this CV hides.
  const hidden = new Set(s.hiddenSubItems ?? []);
  const shown = <T extends { id: string }>(items: T[]) => items.filter((i) => !hidden.has(i.id));
  switch (s.key) {
    case 'profile': {
      const text = richTex(ctx.t(profile.summary, 'the professional summary'));
      return text ? `\\cvsummary{%\n  ${text}%\n}` : null;
    }
    case 'skills': {
      const groups = pick(profile.skills, s);
      const rows = groups
        .map((g) => {
          const cat = tex(ctx.t(g.category, 'a skill category'));
          const items = shown(g.skills)
            .map((sk) => richTex(ctx.t(sk.text, `a skill in "${g.category.en || g.category.fr}"`)))
            .filter(Boolean)
            .join(', ');
          if (!items) return null;
          return macro(inSidebar ? 'cvsidebarskill' : 'cvskillrow', [cat, items]);
        })
        .filter(Boolean);
      return rows.length ? rows.join('\n') : null;
    }
    case 'languages': {
      const langs = pick(profile.languages, s)
        .map((l) => [tex(ctx.t(l.name, 'a language name')), tex(ctx.t(l.level, 'a language level'))] as const)
        .filter(([name]) => name);
      if (!langs.length) return null;
      if (inSidebar) return langs.map(([n, l]) => macro('cvlanguage', [n, l])).join('\n');
      return langs.map(([n, l]) => macro('cvlanguageinline', [n, l])).join('\\cvinlinesep\n') + '\\par';
    }
    case 'studentLife': {
      const groups = pick(profile.studentLife, s);
      const blocks = groups
        .map((g) => {
          const title = tex(ctx.t(g.title, 'a student-life group'));
          const env = g.style === 'lines' ? 'cvlines' : 'cvbullets';
          if (inSidebar) {
            const list = bulletList(ctx, shown(g.items), `"${g.title.en || g.title.fr}"`, env);
            if (!title && !list) return null;
            return [title ? `\\cvsubsection{${title}}` : '', list].filter(Boolean).join('\n');
          }
          const list = bulletList(ctx, shown(g.items), `"${g.title.en || g.title.fr}"`, 'cvbullets');
          return macro('cventry', [title, tex(ctx.t(g.subtitle, 'a student-life subtitle')), '', tex(ctx.t(g.date, 'a date')), '', list], true);
        })
        .filter(Boolean);
      return blocks.length ? blocks.join('\n\n') : null;
    }
    case 'experience': {
      const items = pick(profile.experience, s);
      const blocks = items.map((e) => {
        const where = `experience "${e.title.en || e.title.fr}"`;
        const body = detailBody(
          ctx,
          s.detail,
          richTex(ctx.t(e.description, where)),
          bulletList(ctx, shown(e.bullets), where),
        );
        return macro(
          'cventry',
          [
            tex(ctx.t(e.title, where)),
            tex(ctx.t(e.organization, where)),
            tex(ctx.t(e.location, where)),
            tex(ctx.t(e.date, where)),
            tex(e.tech),
            body,
          ],
          true,
        );
      });
      return blocks.length ? blocks.join('\n\n') : null;
    }
    case 'education': {
      const items = pick(profile.education, s);
      const blocks = items.map((e) => {
        const where = `education "${e.institution.en || e.institution.fr}"`;
        return macro('cveducation', [
          tex(ctx.t(e.institution, where)),
          tex(ctx.t(e.degree, where)),
          tex(ctx.t(e.location, where)),
          tex(ctx.t(e.date, where)),
          richTex(ctx.t(e.details, where)),
        ]);
      });
      return blocks.length ? blocks.join('\n') : null;
    }
    case 'certifications': {
      const items = pick(profile.certifications, s);
      const blocks = items.map((c) => {
        const where = `certification "${c.name.en || c.name.fr}"`;
        return macro('cvcertification', [tex(ctx.t(c.name, where)), tex(ctx.t(c.issuer, where)), tex(ctx.t(c.date, where))]);
      });
      return blocks.length ? blocks.join('\n') : null;
    }
    default: {
      if (!isCustomKey(s.key)) return null;
      const id = s.key.slice('custom:'.length);
      const section = profile.customSections.find((c) => c.id === id);
      if (!section) return null;
      const entries = pick(section.entries, s);
      const blocks = entries.map((e) => {
        const where = `custom entry "${e.title.en || e.title.fr}"`;
        return macro(
          'cventry',
          [tex(ctx.t(e.title, where)), tex(ctx.t(e.subtitle, where)), '', tex(ctx.t(e.date, where)), '', richTex(ctx.t(e.description, where))],
          true,
        );
      });
      return blocks.length ? blocks.join('\n\n') : null;
    }
  }
}

function sectionFileName(s: SectionConfig, profile: Profile): string {
  if (isCustomKey(s.key)) {
    const id = s.key.slice('custom:'.length);
    const section = profile.customSections.find((c) => c.id === id);
    const slug = (section?.title.en || section?.title.fr || id)
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '_')
      .replace(/^_|_$/g, '')
      .slice(0, 40);
    return `custom_${slug || 'section'}_${id.slice(0, 6).replace(/[^a-zA-Z0-9]/g, '')}`;
  }
  return SECTION_FILE[s.key];
}

