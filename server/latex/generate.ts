function fontSpec(cmd: string, f: FontDef, weight: { light: boolean; semibold: boolean }): string {
  const upright = weight.light && f.light ? f.light : f.regular;
  const italic = weight.light && f.lightItalic ? f.lightItalic : f.italic;
  const bold = weight.semibold && f.semibold ? f.semibold : f.bold;
  const boldItalic = weight.semibold && f.semiboldItalic ? f.semiboldItalic : f.boldItalic;
  return [
    `${cmd}{${upright}}[`,
    `  Extension      = ${f.ext},`,
    `  ItalicFont     = ${italic},`,
    `  BoldFont       = ${bold},`,
    `  BoldItalicFont = ${boldItalic},`,
    `  Ligatures      = TeX]`,
  ].join('\n');
}

/** Relative luminance (0 = black, 1 = white) of a 6-digit hex color. */
function luminance(hex: string): number {
  const [r, g, b] = [0, 2, 4].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function settingsFile(cv: CVConfig, theme: string): string {
  const { layout: L, typography: T, colors: C } = cv;
  const body = getFont(T.fontFamily);
  const headingId = T.headingFontFamily || T.fontFamily;
  const heading = getFont(headingId);
  const weight = { light: T.bodyWeight === 'light', semibold: T.boldWeight === 'semibold' };
  const strings = DOC_STRINGS[cv.language];
  const twoCols = L.columns === 2;
  const sidebarRatio = Math.min(0.45, Math.max(0.2, L.sidebarWidth));
  // On a dark sidebar, headings and bullets follow the sidebar text color.
  const darkSidebar = L.sidebarFilled && luminance(hexColor(C.sidebarBg, 'EEF3F9')) < 0.45;
  const sidebarHeading = darkSidebar ? C.sidebarText : C.heading;
  const m = L.margins;

  const lines: string[] = [];
  const add = (...l: string[]) => lines.push(...l);

  add(HEADER_COMMENT('settings.tex -- page geometry, fonts, colors and spacing'));
  add('% --- Page -------------------------------------------------------------');
  add(`\\geometry{paper=${L.paper === 'letter' ? 'letterpaper' : 'a4paper'}, top=${num(m.top)}cm, bottom=${num(m.bottom)}cm, left=${num(m.left)}cm, right=${num(m.right)}cm, footskip=0.8cm}`);
  add('');
  add('% --- Typography -------------------------------------------------------');
  add(`\\linespread{${num(T.lineSpacing, 2)}}`);
  add(fontSpec('\\setmainfont', body, weight));
  if (heading.id !== body.id) {
    add(fontSpec('\\newfontfamily\\cvheadingfamily', heading, { light: false, semibold: weight.semibold }));
    add('\\renewcommand\\cvheadingfont{\\cvheadingfamily}');
  }
  add(`\\setlength\\cvheadingsize{${num(T.headingSize, 1)}pt}`);
  add(`\\setlength\\cvnamesize{${num(T.nameSize, 1)}pt}`);
  add(T.headingUppercase ? '\\cvheadinguppertrue' : '\\cvheadingupperfalse');
  add(T.headingBold ? '\\cvheadingboldtrue' : '\\cvheadingboldfalse');
  add(`\\renewcommand\\cvbodyalign{${T.alignment === 'justify' ? '\\justifying' : '\\RaggedRight'}}`);
  add('');
  add('% --- Colors -----------------------------------------------------------');
  const colors: [string, string, string][] = [
    ['cvprimary', C.primary, '0F3C73'],
    ['cvsecondary', C.secondary, '3C3C3C'],
    ['cvaccent', C.accent, '006EBE'],
    ['cvtext', C.text, '3C3C3C'],
    ['cvheading', C.heading, '0F3C73'],
    ['cvheaderbg', C.headerBg, '0F3C73'],
    ['cvheadertext', C.headerText, 'FFFFFF'],
    ['cvsidebarbg', C.sidebarBg, 'EEF3F9'],
    ['cvsidebartext', C.sidebarText, '2B2B2B'],
    ['cvsidebarheading', sidebarHeading, '0F3C73'],
  ];
  for (const [name, value, fallback] of colors) add(`\\definecolor{${name}}{HTML}{${hexColor(value, fallback)}}`);
  add('\\definecolor{cvdivider}{HTML}{D2D2D2}');
  add('\\colorlet{cvbullet}{cvaccent}');
  add(`\\colorlet{cvsidebarbullet}{${darkSidebar ? 'cvsidebartext' : 'cvaccent'}}`);
  add(`\\colorlet{cvsidebardivider}{${L.sidebarFilled ? 'cvsidebarheading!45!cvsidebarbg' : 'cvdivider'}}`);
  add('\\AtBeginDocument{\\color{cvtext}}');
  add('');
  add('% --- Spacing ----------------------------------------------------------');
  add(`\\setlength\\cvsectionskip{${num(L.sectionSpacing, 1)}pt}`);
  add(`\\setlength\\cventryskip{${num(L.entrySpacing, 1)}pt}`);
  add('');
  add('% --- Photo ------------------------------------------------------------');
  add(`\\renewcommand\\cvphotoshape{${L.photoShape}}`);
  add(`\\setlength\\cvphotosize{${num(L.photoSize, 2)}cm}`);
  if (twoCols) {
    add('');
    add('% --- Columns ----------------------------------------------------------');
    add(`\\cvsetcolumns{${L.sidebarPosition}}{${num(sidebarRatio)}}{${num(1 - sidebarRatio)}}`);
    add(`\\setlength\\columnsep{${L.sidebarFilled ? '1.1cm' : '0.8cm'}}`);
    if (L.columnDivider && !L.sidebarFilled) add('\\setlength\\columnseprule{0.5pt}', '\\colseprulecolor{cvdivider}');
    if (L.sidebarFilled) {
      add('\\cvsidebarfilltrue');
      if (L.headerStyle === 'sidebar' || L.headerStyle === 'main') add('\\cvsidebarfromtoptrue');
    }
  }
  add('');
  add('% --- Page numbering ---------------------------------------------------');
  if (L.pageNumbering === 'none') {
    add('\\pagestyle{empty}');
  } else {
    add('\\usepackage{scrlayer-scrpage}');
    if (L.pageNumbering === 'of-total') add('\\usepackage{lastpage}');
    add('\\clearpairofpagestyles');
    add(
      L.pageNumbering === 'simple'
        ? '\\cfoot*{\\small\\color{cvsecondary}\\thepage}'
        : `\\cfoot*{\\small\\color{cvsecondary}${strings.page}~\\thepage~${strings.of}~\\pageref*{LastPage}}`,
    );
    add('\\pagestyle{scrheadings}');
  }
  add('');
  add('% --- Language-dependent strings --------------------------------------');
  add(`\\renewcommand\\cvtechlabel{${tex(strings.tech)}}`);
  add(`% Theme: ${theme}`);
  return lines.join('\n') + '\n';
}

