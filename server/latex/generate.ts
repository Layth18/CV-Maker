const LINK_ICON: Record<string, string> = {
  linkedin: '\\faLinkedin',
  github: '\\faGithub',
  website: '\\faGlobe',
  portfolio: '\\faBriefcase',
  other: '\\faLink',
};

function shortUrl(url: string): string {
  return url.trim().replace(/^https?:\/\/(www\.)?/i, '').replace(/\/+$/, '');
}

function personalFile(ctx: Ctx, profile: Profile, cv: CVConfig, photo: PhotoAsset | null): string {
  const p = profile.personal;
  const lines = [HEADER_COMMENT('personal_info.tex -- name, headline, contact details and photo')];
  lines.push(`\\cvsetname{${tex(p.firstName)}}{${tex(p.lastName)}}`);
  const headline = tex(ctx.t(p.headline, 'the headline'));
  if (headline) lines.push(`\\cvsetheadline{${headline}}`);
  if (photo && cv.layout.showPhoto) {
    const fit = photo.width > photo.height ? 'height' : 'width';
    lines.push(`\\cvsetphoto[${fit}]{assets/photo.${photo.ext}}`);
  }
  lines.push('');
  lines.push('% \\cvaddcontact{icon}{text}{link}');
  if (p.phone.trim()) lines.push(`\\cvaddcontact{\\faPhone}{${tex(p.phone)}}{${texUrl('tel:' + p.phone.replace(/[^\d+]/g, ''))}}`);
  if (p.email.trim()) lines.push(`\\cvaddcontact{\\faEnvelope}{${tex(p.email)}}{${texUrl('mailto:' + p.email.trim())}}`);
  const location = tex(ctx.t(p.location, 'the location'));
  if (location) lines.push(`\\cvaddcontact{\\faMapMarker*}{${location}}{}`);
  for (const link of p.links) {
    const url = texUrl(link.url);
    if (!url) continue;
    // A label that is itself a URL (or no label) is shown without protocol, "www." and trailing slash.
    const rawLabel = ctx.t(link.label, `link ${link.kind}`) || link.url;
    const label = tex(/^https?:\/\//i.test(rawLabel.trim()) ? shortUrl(rawLabel) : rawLabel);
    lines.push(`\\cvaddcontact{${LINK_ICON[link.kind] ?? LINK_ICON.other}}{${label}}{${url}}`);
  }
  return lines.join('\n') + '\n';
}

