// LaTeX source generation: (bilingual profile, CV configuration) -> modular .tex project.
// Pure and deterministic: the same inputs always produce byte-identical files,
// which lets builds be cached by source hash.

import { DOC_STRINGS, getFont, getTemplate, isCustomKey, sectionLabel, type FontDef } from '../../shared/catalog';
import type {
  CVConfig,
  DetailMode,
  GeneratedFile,
  Lang,
  Localized,
  Profile,
  SectionConfig,
  TextItem,
} from '../../shared/types';
import { hexColor, num, richTex, tex, texUrl } from './escape';

export interface PhotoAsset {
  /** Absolute path of the stored image. */
  sourcePath: string;
  ext: 'png' | 'jpg';
  width: number;
  height: number;
}

export interface GenerateInput {
  profile: Profile;
  cv: CVConfig;
  photo: PhotoAsset | null;
}

export interface GeneratedProject {
  mainFile: string;
  files: GeneratedFile[];
  /** Binary assets to copy next to the sources: project path -> absolute source path. */
  assets: { path: string; sourcePath: string }[];
  /** Non-fatal notes, e.g. missing translations that fell back to the other language. */
  notes: string[];
  /** XeLaTeX runs needed before positions and page totals settle. */
  minPasses: number;
}

/** Static .sty files shipped with every project. */
export const STATIC_STYLE_FILES = ['cvcore.sty', 'cvtheme-classic.sty', 'cvtheme-modern.sty', 'cvtheme-academic.sty', 'cvtheme-compact.sty'];

const SECTION_FILE: Record<string, string> = {
  profile: 'profile',
  skills: 'skills',
  languages: 'languages',
  studentLife: 'student_life',
  experience: 'experience',
  education: 'education',
  certifications: 'certifications',
};

const HEADER_COMMENT = (title: string) =>
  `% ${'='.repeat(74)}\n% ${title}\n% Generated by CV Studio from your profile database. Edit the CV in the app;\n% manual changes here are overwritten on the next generation.\n% ${'='.repeat(74)}\n`;

class Ctx {
  notes = new Set<string>();
  constructor(readonly lang: Lang) {}

  /** Text in the CV language, falling back to the other language with a note. */
  t(value: Localized | undefined, where: string): string {
    if (!value) return '';
    const primary = value[this.lang]?.trim();
    if (primary) return primary;
    const other = value[this.lang === 'en' ? 'fr' : 'en']?.trim();
    if (other) {
      this.notes.add(`Missing ${this.lang.toUpperCase()} text for ${where}; used the ${this.lang === 'en' ? 'French' : 'English'} version.`);
      return other;
    }
    return '';
  }
}

function pick<T extends { id: string }>(items: T[], s: SectionConfig): T[] {
  if (s.itemIds === null) return items;
  const wanted = new Set(s.itemIds);
  return items.filter((i) => wanted.has(i.id));
}

function bulletList(ctx: Ctx, items: TextItem[], where: string, env: 'cvbullets' | 'cvlines' = 'cvbullets'): string {
  const lines = items.map((b) => richTex(ctx.t(b.text, where))).filter(Boolean);
  if (!lines.length) return '';
  return `\\begin{${env}}\n${lines.map((l) => `    \\item ${l}`).join('\n')}\n  \\end{${env}}`;
}

function detailBody(ctx: Ctx, mode: DetailMode, description: string, bullets: string): string {
  let parts: string[];
  if (mode === 'description') parts = [description || bullets];
  else if (mode === 'bullets') parts = [bullets || description];
  else parts = [description, bullets];
  return parts.filter(Boolean).join('\n  ');
}

/** Arguments are each placed on their own line for readability. */
function macro(name: string, args: string[], indentLast = false): string {
  const parts = args.map((a, i) => (indentLast && i === args.length - 1 && a ? `{%\n  ${a}%\n}` : `{${a}}`));
  return `\\${name}${parts.join('')}`;
}

