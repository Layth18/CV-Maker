// ZIP exports built from a stored build's sources, so the archive always
// compiles to the same document as the previewed PDF.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import JSZip from 'jszip';
import { FONTS, getTemplate } from '../shared/catalog';
import type { BuildResult, CVConfig, Profile } from '../shared/types';
import { buildDir } from './builds';

async function addDir(zip: JSZip, dir: string, prefix: string) {
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) await addDir(zip, full, `${prefix}${entry.name}/`);
    else zip.file(`${prefix}${entry.name}`, await fs.readFile(full));
  }
}

function readme(cv: CVConfig | null, build: BuildResult): string {
  const fonts = [cv?.typography.fontFamily, cv?.typography.headingFontFamily]
    .filter(Boolean)
    .map((id) => FONTS.find((f) => f.id === id)?.label)
    .filter(Boolean);
  return `# ${cv?.name ?? 'CV'} — LaTeX project

Generated by CV Studio. This folder compiles to the same PDF that was shown in
the editor preview (build \`${build.buildId}\`, ${build.pageCount ?? '?'} page(s)).

## Compile

Requires a TeX distribution with XeLaTeX (TeX Live 2023+ or MiKTeX).

    latexmk -xelatex main.tex

or, without latexmk, run XeLaTeX ${build.passes > 1 ? 'twice' : 'once'}:

    xelatex main.tex${build.passes > 1 ? '\n    xelatex main.tex' : ''}

LuaLaTeX also works (\`lualatex main.tex\`).

## Structure

| File | Purpose |
| --- | --- |
| \`main.tex\` | Document entry point: class, packages, header and section order |
| \`settings.tex\` | Page geometry, fonts, colors, spacing, page numbering |
| \`personal_info.tex\` | Name, headline, contact details, photo |
| \`sections/*.tex\` | One file per CV section |
| \`custom_preamble.tex\` | Optional advanced LaTeX added in the editor |
| \`cvcore.sty\` | Shared components (headers, entries, columns, sidebar) |
| \`cvtheme-*.sty\` | Themes that style sections and entries |
| \`assets/\` | Images such as the profile photo |

Fonts used: ${fonts.join(', ') || 'see settings.tex'} (bundled with TeX Live; loaded by file name).
Icons come from the \`fontawesome5\` package.
`;
}

export async function sourceZip(build: BuildResult): Promise<Buffer> {
  const zip = new JSZip();
  await addDir(zip, path.join(buildDir(build.buildId), 'source'), '');
  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}

export async function projectZip(build: BuildResult, cv: CVConfig | null, baseName: string): Promise<Buffer> {
  const zip = new JSZip();
  const root = zip.folder(baseName)!;
  const dir = buildDir(build.buildId);
  await addDir(root, path.join(dir, 'source'), '');
  root.file('README.md', readme(cv, build));
  root.file('.latexmkrc', "# Use XeLaTeX\n$pdf_mode = 5;\n");
  const pdf = await fs.readFile(path.join(dir, 'main.pdf')).catch(() => null);
  if (pdf) root.file(`${baseName}.pdf`, pdf);
  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}

/**
 * Recruiter-friendly file name: First_Last_CV_FR, plus the format when the CV
 * has several (e.g. Jane_Doe_CV_EN_Canadian_Standard).
 */
export function cvFileName(profile: Profile, cv: CVConfig | null, build: Pick<BuildResult, 'templateId' | 'language'>): string {
  const person = fileBaseName(`${profile.personal.firstName} ${profile.personal.lastName}`);
  if (!cv || person === 'CV') return fileBaseName(cv?.name ?? 'CV');
  const lang = (build.language ?? cv.language).toUpperCase();
  const parts = [person, 'CV', lang];
  if (cv.formats.length > 1) parts.push(fileBaseName(getTemplate(build.templateId ?? cv.templateId).name));
  return parts.join('_');
}

export function fileBaseName(name: string): string {
  const base = name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 60);
  return base || 'CV';
}
